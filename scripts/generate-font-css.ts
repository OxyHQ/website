/**
 * Capture Bloom's actual web font stylesheet at build time. No duplicate font
 * inventory: the installed package owns faces, weights, fallback stacks and
 * assets. Vite processes these relative URLs through the same asset pipeline
 * as Bloom's runtime imports, so both resolve to the same cached font files.
 */
import { dirname, join, relative } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = join(import.meta.dir, '..');
const output = join(root, 'src/styles/fonts.generated.css');
const fonts = dirname(fileURLToPath(import.meta.resolve('@oxy.so/bloom/fonts')));
const scratch = join(root, 'node_modules/.tmp/bloom-font-css');
await mkdir(scratch, { recursive: true });
const entry = join(scratch, 'entry.ts');
await writeFile(
  entry,
  `
import { applyFontFaces } from ${JSON.stringify(join(fonts, 'apply-font-faces.web.js'))};
import { capturedCss } from 'oxy-font-css-capture';
applyFontFaces();
export default capturedCss;
`,
);
const bundle = await Bun.build({
  entrypoints: [entry],
  target: 'bun',
  plugins: [
    {
      name: 'capture-bloom-font-css',
      setup(build) {
        build.onResolve(
          { filter: /(?:adopt-style-sheet(?:\.js)?$|^oxy-font-css-capture$)/ },
          () => ({
            path: 'capture',
            namespace: 'oxy-font-css',
          }),
        );
        build.onLoad({ filter: /.*/, namespace: 'oxy-font-css' }, () => ({
          contents:
            'export let capturedCss = ""; export function adoptStyleSheet(_id, css) { capturedCss = css; }',
          loader: 'js',
        }));
        build.onLoad({ filter: /\.(woff2?|ttf|otf)$/ }, ({ path }) => ({
          contents: `export default ${JSON.stringify(relative(dirname(output), path).split('\\').join('/'))};`,
          loader: 'js',
        }));
      },
    },
  ],
});
if (!bundle.success) throw new AggregateError(bundle.logs, 'Could not capture Bloom font CSS');
const compiled = join(scratch, 'capture.mjs');
await writeFile(compiled, await bundle.outputs[0].text());
const { default: css } = await import(compiled);
if (
  typeof css !== 'string' ||
  !css.includes('@font-face') ||
  !css.includes('--bloom-font-display:')
) {
  throw new Error('Bloom did not emit a web font stylesheet; check its font API before building.');
}
await writeFile(
  output,
  `/* AUTO-GENERATED by scripts/generate-font-css.ts from Bloom. DO NOT EDIT. */\n${css.trim()}\n`,
);
console.log('[generate-font-css] wrote src/styles/fonts.generated.css');
